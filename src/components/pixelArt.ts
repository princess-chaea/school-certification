Object.assign(ICONS, ACTIVITY_ICONS);

export type IconName = keyof typeof ICONS;

/** 행 단위로 같은 색 픽셀을 이어 붙여 사각형 목록으로 */
export function iconRects(name: string, recolor?: Record<string, string>) {
  const rows = ICONS[name] ?? ICONS.star;
  const rects: Array<{ x: number; y: number; w: number; fill: string }> = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === ".") {
        x++;
        continue;
      }
      let w = 1;
      while (x + w < row.length && row[x + w] === ch) w++;
      rects.push({ x, y, w, fill: recolor?.[ch] ?? PALETTE[ch] ?? "#000" });
      x += w;
    }
  });
  return rects;
}
